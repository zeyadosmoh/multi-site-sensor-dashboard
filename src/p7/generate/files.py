"""Write one Excel file per site per month, with deliberate, documented problems (SYNTHETIC).

Every planted problem is recorded in manifest.json with the exact number of rows the ingestion must reject and
why, so tests can check the validator against ground truth.
"""

import io
import json
import zipfile
from collections import Counter
from dataclasses import dataclass, field
from datetime import date, datetime, time, timedelta
from pathlib import Path

import numpy as np
from openpyxl import Workbook

from p7.generate.simulate import END, EVENTS, START, simulate_all
from p7.generate.sites import MONTHS, SITES

SYNTHETIC_NOTE = "SYNTHETIC DATA - generated by p7 (seeded); not real sensor readings"
FIXED_TIME = datetime(2026, 11, 1, 8, 0, 0)  # workbook metadata + zip timestamps: same seed -> same bytes

# file-level variations
DATE_STYLE = {("JED-02", "2026-07"): "dmy_text", ("MAK-01", "2026-10"): "serial"}
EXTRA_HEADER = {("RUH-02", "2026-06")}
ODD_FILENAME = {("ABH-01", "2026-08"): "sensor_export_final (2).xlsx"}

# row-level problems
OUTAGE = ("BUR-01", datetime(2026, 6, 8, 0), datetime(2026, 6, 9, 23))
STUCK = ("KHB-01", datetime(2026, 8, 5, 2), datetime(2026, 8, 6, 7), 23.4, 41.0)
DUP_EXACT = ("DMM-01", "2026-07", 5)
DUP_CONFLICT = ("MED-01", "2026-09", 3)
IMPOSSIBLE = ("TAB-01", "2026-06")
BAD_DATETIME = ("RUH-01", "2026-05")
OUTSIDE_MONTH = ("HOF-01", "2026-09")


@dataclass
class Row:
    ts: datetime | None
    t: object
    h: object
    raw_date: object = None  # overrides the formatted date cell
    raw_time: object = None


@dataclass
class FileSpec:
    site: str
    month: str
    filename: str
    sheet: str
    cover_sheet: bool
    time_style: str
    date_style: str
    extra_header: bool
    rows: list[Row] = field(default_factory=list)
    expected_rejects: Counter = field(default_factory=Counter)
    problems: list[str] = field(default_factory=list)
    dropped_hours: int = 0

    @property
    def expected_readings(self) -> int:
        # distinct hours that survive validation
        return len({r.ts for r in self.rows if r.ts is not None}) - self._lost_hours

    _lost_hours: int = 0


def month_bounds(month: str) -> tuple[datetime, datetime]:
    y, m = map(int, month.split("-"))
    a = datetime(y, m, 1)
    b = datetime(y + (m == 12), m % 12 + 1, 1)
    return a, b


def _idx(ts: datetime) -> int:
    return int((ts - START).total_seconds() // 3600)


def build_specs(seed: int) -> list[FileSpec]:
    series = simulate_all(seed)
    rng = np.random.default_rng(seed + 1000)
    specs: list[FileSpec] = []
    for si, site in enumerate(SITES):
        temp, hum = series[site.code]
        # make the stuck run unmistakable: neighbours differ from the stuck value
        if site.code == STUCK[0]:
            a, b = _idx(STUCK[1]), _idx(STUCK[2]) + 1
            temp[a:b], hum[a:b] = STUCK[3], STUCK[4]
            for k in (a - 1, b):
                if temp[k] == STUCK[3]:
                    temp[k] += 0.3
        for mi, month in enumerate(MONTHS):
            key = (site.code, month)
            spec = FileSpec(
                site=site.code, month=month,
                filename=ODD_FILENAME.get(key, f"{site.code}_{month}.xlsx"),
                sheet="Readings" if (si + mi) % 4 else "Sheet1",
                cover_sheet=key in ODD_FILENAME or (si + mi) % 3 == 0,
                time_style="time" if si % 2 else "text",
                date_style=DATE_STYLE.get(key, "date"),
                extra_header=key in EXTRA_HEADER,
            )
            a, b = month_bounds(month)
            hours = [a + timedelta(hours=i) for i in range(int((b - a).total_seconds() // 3600))]
            protected: set[datetime] = set()

            if site.code == OUTAGE[0] and a <= OUTAGE[1] < b:
                gone = {h for h in hours if OUTAGE[1] <= h <= OUTAGE[2]}
                hours = [h for h in hours if h not in gone]
                spec.dropped_hours += len(gone)
                spec.problems.append(f"sensor outage: {len(gone)} missing hours {OUTAGE[1]:%Y-%m-%d %H:%M} .. "
                                     f"{OUTAGE[2]:%Y-%m-%d %H:%M}")
            if site.code == STUCK[0] and a <= STUCK[1] < b:
                protected |= {h for h in hours if STUCK[1] - timedelta(hours=1) <= h <= STUCK[2] + timedelta(hours=1)}
                spec.problems.append(f"stuck sensor: {STUCK[3]} C / {STUCK[4]} % from {STUCK[1]:%Y-%m-%d %H:%M} "
                                     f"to {STUCK[2]:%Y-%m-%d %H:%M} (30 readings)")

            # scattered missing hours (~0.4%), away from the first/last day and protected windows
            candidates = [h for h in hours if h not in protected and a + timedelta(days=1) <= h < b - timedelta(days=1)]
            n_gaps = int(rng.integers(1, 6))
            gaps = set(rng.choice(len(candidates), size=n_gaps, replace=False).tolist())
            gap_hours = {candidates[i] for i in gaps}
            hours = [h for h in hours if h not in gap_hours]
            spec.dropped_hours += n_gaps
            spec.problems.append(f"{n_gaps} scattered missing hours")
            protected |= gap_hours

            spec.rows = [Row(h, float(temp[_idx(h)]), float(hum[_idx(h)])) for h in hours]
            _plant_row_problems(spec, rng, protected)
            # trailing empty rows that a real export often has; they must be ignored, not rejected
            if (si + mi) % 5 == 0:
                spec.rows += [Row(None, None, None, raw_date=None, raw_time=None)] * 3
            specs.append(spec)
    return specs


def _pick(spec: FileSpec, rng: np.random.Generator, n: int, protected: set[datetime]) -> list[int]:
    a, b = month_bounds(spec.month)
    idx = [i for i, r in enumerate(spec.rows)
           if r.ts is not None and r.ts not in protected and a + timedelta(days=2) <= r.ts < b - timedelta(days=2)]
    chosen = sorted(rng.choice(len(idx), size=n, replace=False).tolist())
    picked = [idx[i] for i in chosen]
    protected |= {spec.rows[i].ts for i in picked}
    return picked


def _plant_row_problems(spec: FileSpec, rng: np.random.Generator, protected: set[datetime]) -> None:
    key = (spec.site, spec.month)
    if key == DUP_EXACT[:2]:
        picked = _pick(spec, rng, DUP_EXACT[2], protected)
        for i in reversed(picked):
            r = spec.rows[i]
            spec.rows.insert(i + 1, Row(r.ts, r.t, r.h))
        spec.expected_rejects["duplicate_exact"] += DUP_EXACT[2]
        spec.problems.append(f"{DUP_EXACT[2]} exact duplicate rows (first copy kept)")
    if key == DUP_CONFLICT[:2]:
        picked = _pick(spec, rng, DUP_CONFLICT[2], protected)
        for i in reversed(picked):
            r = spec.rows[i]
            spec.rows.insert(i + 1, Row(r.ts, round(r.t + 1.3, 1), r.h))
        spec.expected_rejects["duplicate_conflict"] += 2 * DUP_CONFLICT[2]
        spec._lost_hours += DUP_CONFLICT[2]
        spec.problems.append(f"{DUP_CONFLICT[2]} hours with two different values (both rows rejected)")
    if key == IMPOSSIBLE:
        bad = [("t", 85.0, "temp_impossible"), ("t", -60.0, "temp_impossible"),
               ("h", 120.0, "humidity_impossible"), ("h", -5.0, "humidity_impossible"),
               ("t", None, "missing_value"), ("t", "ERR", "non_numeric")]
        for i, (col, value, reason) in zip(_pick(spec, rng, len(bad), protected), bad, strict=True):
            setattr(spec.rows[i], col, value)
            spec.expected_rejects[reason] += 1
        spec._lost_hours += len(bad)
        spec.problems.append("impossible values: 85.0 C, -60.0 C, 120 %, -5 %, a blank and 'ERR'")
    if key == BAD_DATETIME:
        i, j = _pick(spec, rng, 2, protected)
        spec.rows[i].raw_date = "2026-13-01"
        spec.rows[j].raw_time = "25:00"
        spec.expected_rejects["bad_date"] += 1
        spec.expected_rejects["bad_time"] += 1
        spec._lost_hours += 2
        spec.problems.append("one impossible date (2026-13-01) and one impossible time (25:00)")
    if key == OUTSIDE_MONTH:
        last = spec.rows[-1]
        for k in (1, 2):
            spec.rows.append(Row(last.ts + timedelta(hours=k), last.t, last.h))
        spec.expected_rejects["outside_file_month"] += 2
        spec._lost_hours += 2
        spec.problems.append("2 rows from the next month copied at the end")
    if spec.extra_header:
        spec.problems.append("extra title row and a blank row above the header")
    if spec.date_style != "date":
        spec.problems.append({"dmy_text": "dates as DD/MM/YYYY text",
                              "serial": "dates as plain Excel serial numbers"}[spec.date_style])
    if spec.filename != f"{spec.site}_{spec.month}.xlsx":
        spec.problems.append("filename without site/month; only the Info cover sheet identifies it")


def _date_cell(ts: datetime, style: str):
    if style == "dmy_text":
        return ts.strftime("%d/%m/%Y")
    if style == "serial":
        return (ts.date() - date(1899, 12, 30)).days
    return ts.date()


def _time_cell(ts: datetime, style: str):
    return time(ts.hour, ts.minute) if style == "time" else ts.strftime("%H:%M")


def write_workbook(spec: FileSpec) -> bytes:
    wb = Workbook()
    wb.properties.creator = "p7 synthetic generator"
    wb.properties.title = f"SYNTHETIC sensor export {spec.site} {spec.month}"
    wb.properties.created = wb.properties.modified = FIXED_TIME
    data = wb.active
    data.title = spec.sheet
    if spec.cover_sheet:
        info = wb.create_sheet("Info", 0)
        for row in (("Site code", spec.site), ("Month", spec.month), ("Exported by", "BMS export tool"),
                    ("Note", SYNTHETIC_NOTE)):
            info.append(row)
    if spec.extra_header:
        data.append([f"Sensor export - {spec.site} - {spec.month}", None, None, None, None, SYNTHETIC_NOTE])
        data.append([])
        data.append(["Date", "Time", "Temperature", "Humidity"])
    else:
        data.append(["Date", "Time", "Temperature", "Humidity", None, SYNTHETIC_NOTE])
    for r in spec.rows:
        if r.ts is None:
            data.append([None, None, None, None])
            continue
        d = r.raw_date if r.raw_date is not None else _date_cell(r.ts, spec.date_style)
        t = r.raw_time if r.raw_time is not None else _time_cell(r.ts, spec.time_style)
        data.append([d, t, r.t, r.h])
        if isinstance(d, date):
            data.cell(row=data.max_row, column=1).number_format = "yyyy-mm-dd"
        if isinstance(t, time):
            data.cell(row=data.max_row, column=2).number_format = "hh:mm"
    buf = io.BytesIO()
    wb.save(buf)
    return _normalise_zip(buf.getvalue())


def _normalise_zip(xlsx: bytes) -> bytes:
    """Rewrite the xlsx container with fixed timestamps so the same seed gives byte-identical files."""
    src = zipfile.ZipFile(io.BytesIO(xlsx))
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as dst:
        for info in src.infolist():
            content = src.read(info.filename)
            if info.filename == "docProps/core.xml":
                content = _fix_core_dates(content)
            zi = zipfile.ZipInfo(info.filename, date_time=FIXED_TIME.timetuple()[:6])
            zi.compress_type = zipfile.ZIP_DEFLATED
            dst.writestr(zi, content)
    return out.getvalue()


def _fix_core_dates(xml: bytes) -> bytes:
    import re

    stamp = FIXED_TIME.strftime("%Y-%m-%dT%H:%M:%SZ").encode()
    return re.sub(rb"(<dcterms:(?:created|modified)[^>]*>)[^<]*(<)", rb"\g<1>" + stamp + rb"\g<2>", xml)


def generate(out_dir: Path, seed: int) -> dict:
    xlsx_dir = out_dir / "xlsx"
    xlsx_dir.mkdir(parents=True, exist_ok=True)
    for old in xlsx_dir.glob("*.xlsx"):
        old.unlink()
    specs = build_specs(seed)
    files = []
    for spec in specs:
        (xlsx_dir / spec.filename).write_bytes(write_workbook(spec))
        data_rows = sum(1 for r in spec.rows if r.ts is not None)
        files.append({
            "filename": spec.filename, "site": spec.site, "month": spec.month,
            "sheet": spec.sheet, "cover_sheet": spec.cover_sheet, "date_style": spec.date_style,
            "time_style": spec.time_style, "extra_header": spec.extra_header,
            "data_rows": data_rows, "missing_hours": spec.dropped_hours,
            "expected_readings": spec.expected_readings,
            "expected_rejects": dict(sorted(spec.expected_rejects.items())),
            "problems": spec.problems,
        })
    manifest = {
        "notice": SYNTHETIC_NOTE,
        "seed": seed,
        "period": {"start": START.isoformat(), "end_exclusive": END.isoformat(), "timezone": "Asia/Riyadh"},
        "files": files,
        "totals": {
            "files": len(files),
            "data_rows": sum(f["data_rows"] for f in files),
            "expected_readings": sum(f["expected_readings"] for f in files),
            "expected_rejects": dict(sorted(sum((Counter(f["expected_rejects"]) for f in files), Counter()).items())),
        },
        "stuck_runs": [{"site": STUCK[0], "start": STUCK[1].isoformat(), "end": STUCK[2].isoformat(),
                        "readings": int((STUCK[2] - STUCK[1]).total_seconds() // 3600) + 1,
                        "temperature": STUCK[3], "humidity": STUCK[4]}],
        "outages": [{"site": OUTAGE[0], "start": OUTAGE[1].isoformat(), "end": OUTAGE[2].isoformat()}],
        "events": [{"site": e.site, "kind": e.kind, "start": e.start.isoformat(), "end": e.end.isoformat(),
                    "note": e.note} for e in EVENTS],
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


def write_sample_zip(out_dir: Path, month: str, zip_path: Path) -> Path:
    """Zip every file of one month (the committed sample)."""
    manifest = json.loads((out_dir / "manifest.json").read_text())
    names = sorted(f["filename"] for f in manifest["files"] if f["month"] == month)
    zip_path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(zip_path, "w", zipfile.ZIP_DEFLATED) as z:
        for name in names:
            zi = zipfile.ZipInfo(name, date_time=FIXED_TIME.timetuple()[:6])
            zi.compress_type = zipfile.ZIP_DEFLATED
            z.writestr(zi, (out_dir / "xlsx" / name).read_bytes())
    return zip_path
